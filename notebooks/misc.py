def plot_map(da, area, grd, label, vmin=None, vmax=None, suptitle='',
             nh='JFM', sh='JAS', cmap='coolwarm'):

  sMin, sMax, sMean, sStd, sRMS = myStats(np.ma.masked_invalid(da), area)
  try:
    cmap_masked = getattr(plt.cm, cmap).copy()
    cmap_masked.set_bad(color='gray')
  except AttributeError:
    print(f"Colormap '{cmap}' not found. Using default 'viridis'.")
    cmap_masked = plt.cm.viridis.copy()
    cmap_masked.set_bad(color='gray')

  fig = plt.figure(figsize=(10, 5))
  ax = fig.add_subplot(1, 1, 1, projection=ccrs.PlateCarree())
  # Add land feature to color continents
  ax.add_feature(cfeature.LAND, facecolor='lightgray')
  plt.suptitle(suptitle)
  pc = ax.pcolormesh(grd.geolon_c, grd.geolat_c, da,
                transform=ccrs.PlateCarree(),vmin=vmin, vmax=vmax,
                cmap=cmap)

  #ax.set_title(label + ', '+ da.description)
  ax.set_title(label)
  annotateStats(ax, sMin, sMax, sMean, sStd, sRMS)
  add_labels(ax, nh=nh, sh=sh)
  cax = fig.add_axes([0.91, 0.22, 0.02, 0.45])
  cbar = plt.colorbar(pc, cax=cax, label='[m]')
  cbar.ax.tick_params(labelsize=12)
  ax.set_global()
  ax.stock_img()
  ax.coastlines()
  # Add gridlines for latitude and longitude
  gl = ax.gridlines(draw_labels=True, linewidth=0.5, color='black', alpha=0.0, linestyle='--')
  # Customize gridline labels
  gl.top_labels = False    # Turn off labels at the top
  gl.right_labels = False  # Turn off labels on the right
  gl.xlabel_style = {'size': 10, 'color': 'black'}
  gl.ylabel_style = {'size': 10, 'color': 'black'};

  return

