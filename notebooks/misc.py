def plot_transport_time_series(ds, section_name, labels, to_yearly=False, observed_values=None):
    """
    Plot the time series of transport for a given section, with options for yearly aggregation
    and overlaying observed ranges or mean values.

    Parameters:
        ds (xarray.Dataset): Dataset containing the 'transport' variable with
                             dimensions (sections, time).
        section_name (str): Name of the section to plot.
        to_yearly (bool): If True, aggregates the time series to yearly means.
        observed_values (tuple or float, optional): Observed range (min, max) or mean value
                                                    to overlay on the plot.
    """
    plt.figure(figsize=(10, 6))
    for i in range(len(labels)):
        
        # Check if the section exists
        if ('h.'+section_name) not in ds[i].sections.values:
            print(f"Section '{section_name}' not found in the '{labels[i]}' dataset. Skipping plot.")
            return
    
        # Check for required dimensions and variables
        if "sections" not in ds[i].dims or "time" not in ds[i].dims:
            raise ValueError("Dataset must contain 'sections' and 'time' dimensions.")
        if "transport" not in ds[i].data_vars:
            raise ValueError("Dataset must contain 'transport' as a data variable.")
    
        section_data = ds[i].sel(sections='h.'+section_name)
        transport = section_data["transport"]
        # Convert to yearly time series if requested
        if to_yearly:
            section_data = weighted_temporal_mean(section_data,'transport')
            transport = section_data
            
        # Plot the time series
        plt.plot(section_data["time"], transport, label=f"Case: {labels[i]}", lw=2)
        
    plt.xlabel("Time")
    plt.ylabel("Transport (Sv)")
    plt.title(f"Volume Transport Across {section_name}")
    plt.grid()
    plt.legend()
     # Overlay observed range or mean
    if observed_values is not None:
        if isinstance(observed_values, (tuple, list)) and len(observed_values) == 2:
            plt.axhspan(
                observed_values[0], observed_values[1], color="gray", alpha=0.2,
                label=f"Observed Range: {observed_values[0]} to {observed_values[1]}"
            )
        elif isinstance(observed_values, (int, float)):
            plt.axhline(
                observed_values, color="red", linestyle="--", label=f"Observed Mean: {observed_values}"
            )
        else:
            raise ValueError("Observed values must be a tuple (min, max) or a single numeric mean.")

       
    return

def get_transport_range_or_mean(config_value):
    """
    Given a transport section from diag_config_yml, return either (min, max) or mean,
    handling the case of 'None' as a special case.
    
    Args:
    config_value: list, the transport configuration (e.g., ['umo', 2.0, 3.0] or ['umo', 'None'])
    
    Returns:
    Tuple or mean value, depending on the configuration.
    """
    if 'None' in config_value:  # Check if 'None' is in the list
        return None  # Return None or any other default you'd like for this case
    elif len(config_value) == 2:
        try:
            return float(config_value[1])  # If there's one value, return it as the mean
        except ValueError:
            raise ValueError(f"Invalid value in config: {config_value[1]} cannot be converted to float.")
    elif len(config_value) == 3:
        try:
            return (float(config_value[1]), float(config_value[2]))  # Min, Max case
        except ValueError:
            raise ValueError(f"Invalid values in config: {config_value[1]} or {config_value[2]} cannot be converted to float.")
    else:
        raise ValueError("Invalid configuration format")

	
